// Discover Your Tone licence core — shared by Licence Desk (browser) and tests (Node).
// Produces exactly the same keys as dyt_licence.py.
(function (root) {
  const PREFIX = "DYT-ER-";
  const EDITIONS = { founder: "F", standard: "S" };
  const LEDGER_FIELDS = ["serial", "edition", "name", "email", "order_id", "issued", "key"];
  const subtle = (root.crypto || globalThis.crypto).subtle;

  const b64u = (bytes) => {
    let s = "";
    for (const b of bytes) s += String.fromCharCode(b);
    return btoa(s).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
  };
  const unb64u = (s) => {
    const bin = atob(s.replace(/-/g, "+").replace(/_/g, "/") + "=".repeat((4 - (s.length % 4)) % 4));
    return Uint8Array.from(bin, (c) => c.charCodeAt(0));
  };
  const clean = (v) => String(v ?? "").replace(/[|\r\n\t]/g, " ").trim();
  const today = () => new Date().toISOString().slice(0, 10);

  // ── Keys ────────────────────────────────────────────────────────────────
  async function generateKeyPair(label) {
    const kp = await subtle.generateKey({ name: "Ed25519" }, true, ["sign", "verify"]);
    const jwk = await subtle.exportKey("jwk", kp.privateKey);
    return { kty: "OKP", crv: "Ed25519", d: jwk.d, x: jwk.x, label: label || `created ${today()}` };
  }

  async function importPrivate(jwk) {
    if (!jwk || jwk.crv !== "Ed25519" || !jwk.d || !jwk.x) throw new Error("That isn't an Engine Room signing key file.");
    return subtle.importKey("jwk", { kty: "OKP", crv: "Ed25519", d: jwk.d, x: jwk.x }, { name: "Ed25519" }, false, ["sign"]);
  }

  async function importPublicRaw(bytes) {
    return subtle.importKey("raw", bytes, { name: "Ed25519" }, false, ["verify"]);
  }

  function headerFor(jwk) {
    const pub = unb64u(jwk.x);
    const rows = [];
    for (let i = 0; i < 32; i += 8)
      rows.push(Array.from(pub.slice(i, i + 8), (b) => "0x" + b.toString(16).padStart(2, "0")).join(", "));
    return `#pragma once
// Generated by Licence Desk — ${jwk.label}
// Public half of the Engine Room signing key. Safe to ship.
#include <cstdint>

namespace LicencePublicKey
{
    inline constexpr uint8_t bytes[32] =
    {
    ${rows.join(",\n    ")}
    };
    inline constexpr const char* label = "${jwk.label}";
}
`;
  }

  function publicFromHeader(text) {
    const hex = [...text.matchAll(/0x([0-9a-fA-F]{2})/g)].slice(0, 32).map((m) => parseInt(m[1], 16));
    return new Uint8Array(hex);
  }

  // ── Signing ─────────────────────────────────────────────────────────────
  async function makeKey(privKey, edition, serial, name, email, issued) {
    const payload = ["1", "ER", EDITIONS[edition], String(serial), clean(name), clean(email).toLowerCase(), issued].join("|");
    const data = new TextEncoder().encode(payload);
    const sig = new Uint8Array(await subtle.sign({ name: "Ed25519" }, privKey, data));
    return `${PREFIX}${b64u(data)}.${b64u(sig)}`;
  }

  async function verifyKey(text, pubKey) {
    const at = String(text).indexOf(PREFIX);
    if (at < 0) throw new Error("not an Engine Room key");
    const key = String(text).slice(at).split(/\n\s*\n/)[0].replace(/\s+/g, "");
    const [p, s] = key.slice(PREFIX.length).split(".");
    if (!p || !s) throw new Error("incomplete key");
    const data = unb64u(p), sig = unb64u(s);
    if (b64u(data) !== p || b64u(sig) !== s) throw new Error("key is not in canonical form");
    if (!(await subtle.verify({ name: "Ed25519" }, pubKey, sig, data))) throw new Error("signature does not match");
    const f = new TextDecoder().decode(data).split("|");
    return { version: f[0], product: f[1], edition: f[2] === "F" ? "founder" : "standard", serial: +f[3], name: f[4], email: f[5], issued: f[6] };
  }

  // ── CSV ─────────────────────────────────────────────────────────────────
  function parseCSV(text) {
    const rows = []; let row = [], field = "", q = false;
    text = text.replace(/^﻿/, "");
    for (let i = 0; i < text.length; i++) {
      const c = text[i];
      if (q) {
        if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
        else if (c === '"') q = false;
        else field += c;
      } else if (c === '"') q = true;
      else if (c === ",") { row.push(field); field = ""; }
      else if (c === "\n" || c === "\r") {
        if (c === "\r" && text[i + 1] === "\n") i++;
        row.push(field); field = "";
        if (row.some((v) => v.trim() !== "")) rows.push(row);
        row = [];
      } else field += c;
    }
    row.push(field);
    if (row.some((v) => v.trim() !== "")) rows.push(row);
    if (!rows.length) return [];
    const head = rows[0].map((h) => h.trim().toLowerCase().replace(/[\s-]+/g, "_"));
    return rows.slice(1).map((r) => Object.fromEntries(head.map((h, i) => [h, (r[i] ?? "").trim()])));
  }

  function toCSV(rows, fields) {
    const esc = (v) => { v = String(v ?? ""); return /[",\r\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v; };
    return [fields.join(","), ...rows.map((r) => fields.map((f) => esc(r[f])).join(","))].join("\r\n") + "\r\n";
  }

  // Works with HighLevel, Shopify, Stripe and most store exports.
  function buyerFromRow(r) {
    const pick = (...ks) => { for (const k of ks) if (r[k]) return r[k]; return ""; };
    const email = pick("email", "email_address", "customer_email", "contact_email");
    const first = pick("first_name", "firstname", "billing_first_name");
    const last = pick("last_name", "lastname", "billing_last_name");
    const name = pick("name", "full_name", "customer_name", "billing_name") || [first, last].filter(Boolean).join(" ") || email.split("@")[0];
    const order = pick("order_id", "order", "order_number", "name_order", "transaction_id", "id");
    const edition = (pick("edition") || "").toLowerCase();
    return { email, name, order_id: order, edition };
  }

  async function issue(privKey, ledger, buyer, defaultEdition) {
    const edition = EDITIONS[buyer.edition] ? buyer.edition : defaultEdition;
    const email = clean(buyer.email).toLowerCase();
    const existing = ledger.find((r) => r.email.toLowerCase() === email && r.order_id === (buyer.order_id || "") && r.edition === edition);
    if (existing) return { row: existing, isNew: false };
    const serial = 1 + Math.max(0, ...ledger.filter((r) => r.edition === edition).map((r) => +r.serial));
    const issued = today();
    const key = await makeKey(privKey, edition, serial, buyer.name, email, issued);
    const row = { serial, edition, name: clean(buyer.name), email, order_id: buyer.order_id || "", issued, key };
    ledger.push(row);
    return { row, isNew: true };
  }

  function licenceFileText(row) {
    const tag = row.edition === "founder" ? `Founder #${String(row.serial).padStart(3, "0")}` : `Licence #${row.serial}`;
    return `# The Engine Room — Discover Your Tone\n# ${tag}, licensed to ${row.name}\n# Open the plugin, click ACTIVATE, and drop this file on it (or paste the key).\n\n${row.key}\n`;
  }

  function fileStem(row) {
    return `${row.edition === "founder" ? "F" : "S"}${String(row.serial).padStart(3, "0")}-${row.name.replace(/[^A-Za-z0-9]+/g, "-").replace(/^-|-$/g, "") || "buyer"}`;
  }

  const api = { PREFIX, EDITIONS, LEDGER_FIELDS, b64u, unb64u, generateKeyPair, importPrivate, importPublicRaw, headerFor,
    publicFromHeader, makeKey, verifyKey, parseCSV, toCSV, buyerFromRow, issue, licenceFileText, fileStem };
  if (typeof module !== "undefined") module.exports = api; else root.DytLicence = api;
})(typeof window !== "undefined" ? window : globalThis);
