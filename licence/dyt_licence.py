#!/usr/bin/env python3
"""
Discover Your Tone licence tool — issues signed Engine Room keys.

Keys are signed with Ed25519. The plugin carries only the PUBLIC key, so keys
can be checked offline and can't be forged without the private key file.

  python3 dyt_licence.py init                         # once, before issuing real keys
  python3 dyt_licence.py issue --name "Sam Lee" --email sam@x.com --edition founder
  python3 dyt_licence.py batch presale_buyers.csv     # columns: email,name,order_id[,edition]
  python3 dyt_licence.py verify "DYT-ER-...."

Needs:  pip install cryptography
KEEP keys/engine-room-private.jwk SECRET AND BACKED UP. Lose it and you can't issue
keys that the shipped plugin accepts. Leak it and anyone can make keys.
"""
import argparse, base64, csv, datetime, json, os, re, sys
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey, Ed25519PublicKey
from cryptography.hazmat.primitives import serialization
from cryptography.exceptions import InvalidSignature

HERE        = Path(__file__).resolve().parent
ROOT        = HERE.parent
KEY_FILE    = HERE / "keys" / "engine-room-private.jwk"
HEADER_FILE = ROOT / "Source" / "LicencePublicKey.h"
LEDGER      = HERE / "issued_ledger.csv"
OUTBOX      = HERE / "outbox"

PRODUCT  = "ER"
PREFIX   = "DYT-ER-"
EDITIONS = {"founder": "F", "standard": "S"}
LEDGER_FIELDS = ["serial", "edition", "name", "email", "order_id", "issued", "key"]


def b64u(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()

def unb64u(s: str) -> bytes:
    return base64.urlsafe_b64decode(s + "=" * (-len(s) % 4))

def clean(field: str) -> str:
    return re.sub(r"[|\r\n\t]", " ", field or "").strip()


# ── Keys ──────────────────────────────────────────────────────────────────────
def load_private() -> Ed25519PrivateKey:
    if not KEY_FILE.exists():
        sys.exit(f"No private key at {KEY_FILE}. Run:  python3 dyt_licence.py init")
    jwk = json.loads(KEY_FILE.read_text())
    return Ed25519PrivateKey.from_private_bytes(unb64u(jwk["d"]))

def public_raw(priv: Ed25519PrivateKey) -> bytes:
    return priv.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)

def public_from_header() -> Ed25519PublicKey:
    hexes = re.findall(r"0x([0-9a-fA-F]{2})", HEADER_FILE.read_text())
    return Ed25519PublicKey.from_public_bytes(bytes(int(h, 16) for h in hexes[:32]))

def write_header(pub: bytes, label: str):
    rows = ",\n    ".join(", ".join(f"0x{b:02x}" for b in pub[i:i + 8]) for i in range(0, 32, 8))
    HEADER_FILE.write_text(f"""#pragma once
// Generated by licence/dyt_licence.py init — {label}
// Public half of the Engine Room signing key. Safe to ship.
#include <cstdint>

namespace LicencePublicKey
{{
    inline constexpr uint8_t bytes[32] =
    {{
    {rows}
    }};
    inline constexpr const char* label = "{label}";
}}
""")

def cmd_init(args):
    if KEY_FILE.exists() and not args.force:
        sys.exit("A private key already exists. Re-running init would invalidate every key "
                 "you've issued. Use --force only if you really mean it.")
    KEY_FILE.parent.mkdir(parents=True, exist_ok=True)
    priv = Ed25519PrivateKey.generate()
    seed = priv.private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw,
                              serialization.NoEncryption())
    pub = public_raw(priv)
    label = args.label or f"created {datetime.date.today().isoformat()}"
    KEY_FILE.write_text(json.dumps({"kty": "OKP", "crv": "Ed25519", "d": b64u(seed), "x": b64u(pub),
                                    "label": label}, indent=2))
    os.chmod(KEY_FILE, 0o600)
    write_header(pub, label)
    print(f"Private key: {KEY_FILE}   (back this up somewhere safe, never upload it)")
    print(f"Public key written to {HEADER_FILE}. Rebuild the plugin so it accepts the new keys.")


# ── Issuing ───────────────────────────────────────────────────────────────────
def read_ledger():
    if not LEDGER.exists():
        return []
    with LEDGER.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))

def append_ledger(row):
    new = not LEDGER.exists()
    with LEDGER.open("a", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=LEDGER_FIELDS)
        if new: w.writeheader()
        w.writerow(row)

def make_key(priv, edition, serial, name, email, issued) -> str:
    payload = "|".join(["1", PRODUCT, EDITIONS[edition], str(serial), clean(name), clean(email).lower(), issued])
    data = payload.encode("utf-8")
    return f"{PREFIX}{b64u(data)}.{b64u(priv.sign(data))}"

def licence_file_text(key, name, edition, serial):
    tag = f"Founder #{serial:03d}" if edition == "founder" else f"Licence #{serial}"
    return (f"# The Engine Room — Discover Your Tone\n"
            f"# {tag}, licensed to {name}\n"
            f"# Open the plugin, click ACTIVATE, and drop this file on it (or paste the key).\n\n"
            f"{key}\n")

def email_text(name, key, edition, serial):
    first = (name.split() or ["there"])[0]
    founder = (f"You're Founder #{serial:03d}. That number shows on your pedal in the plugin, "
               f"and it's yours for good.\n\n") if edition == "founder" else ""
    return f"""Subject: Your Engine Room key is here.

Hey {first},

Thanks for backing The Engine Room early. {founder}Here's how to get it running:

1. Download the installer for Mac or Windows from your account page.
2. Open it in your DAW (or the standalone app) and click ACTIVATE.
3. Paste this key, or drop the attached .dytlicence file onto the pedal:

{key}

One key covers all your own computers. Keep this email somewhere safe.

Find your sound,
Kyle
Discover Your Tone
"""

def issue_one(priv, ledger, name, email, edition, order_id=""):
    if edition not in EDITIONS:
        raise ValueError(f"edition must be one of {list(EDITIONS)}")
    for row in ledger:
        if row["email"].lower() == email.lower() and row["order_id"] == order_id and row["edition"] == edition:
            return row, False   # already issued: same key every time
    serial = 1 + max([int(r["serial"]) for r in ledger if r["edition"] == edition] or [0])
    issued = datetime.date.today().isoformat()
    key = make_key(priv, edition, serial, name, email, issued)
    row = {"serial": serial, "edition": edition, "name": clean(name), "email": clean(email).lower(),
           "order_id": order_id, "issued": issued, "key": key}
    append_ledger(row)
    ledger.append(row)
    return row, True

def write_outputs(row):
    OUTBOX.mkdir(exist_ok=True)
    (OUTBOX / "licence_files").mkdir(exist_ok=True)
    (OUTBOX / "emails").mkdir(exist_ok=True)
    serial, edition = int(row["serial"]), row["edition"]
    stem = f"{'F' if edition == 'founder' else 'S'}{serial:03d}-{re.sub(r'[^A-Za-z0-9]+', '-', row['name']).strip('-') or 'buyer'}"
    (OUTBOX / "licence_files" / f"{stem}.dytlicence").write_text(licence_file_text(row["key"], row["name"], edition, serial), encoding="utf-8")
    (OUTBOX / "emails" / f"{stem}.txt").write_text(email_text(row["name"], row["key"], edition, serial), encoding="utf-8")

def write_crm_export(ledger):
    """CSV ready to import into HighLevel (or any CRM) as custom fields."""
    OUTBOX.mkdir(exist_ok=True)
    with (OUTBOX / "crm_import.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["email", "name", "order_id", "engine_room_edition", "engine_room_number", "engine_room_licence_key"])
        for r in ledger:
            w.writerow([r["email"], r["name"], r["order_id"], r["edition"], r["serial"], r["key"]])

def cmd_issue(args):
    priv = load_private()
    ledger = read_ledger()
    row, new = issue_one(priv, ledger, args.name, args.email, args.edition, args.order or "")
    write_outputs(row)
    write_crm_export(ledger)
    print(("Issued" if new else "Already issued (same key)") + f": {row['edition']} #{row['serial']} for {row['name']}")
    print(row["key"])

def cmd_batch(args):
    priv = load_private()
    ledger = read_ledger()
    made = skipped = 0
    with open(args.csv, newline="", encoding="utf-8-sig") as f:
        for i, r in enumerate(csv.DictReader(f), start=2):
            r = {k.strip().lower(): (v or "").strip() for k, v in r.items() if k}
            email = r.get("email", "")
            if not email or "@" not in email:
                print(f"  row {i}: skipped (no valid email)"); continue
            name = r.get("name") or " ".join(filter(None, [r.get("first_name"), r.get("last_name")])) or email.split("@")[0]
            edition = (r.get("edition") or args.edition).lower()
            row, new = issue_one(priv, ledger, name, email, edition, r.get("order_id", ""))
            write_outputs(row)
            made += new; skipped += (not new)
    write_crm_export(ledger)
    print(f"Done: {made} new keys, {skipped} already issued. See {OUTBOX}/")


# ── Verifying ─────────────────────────────────────────────────────────────────
def verify(key: str, pub: Ed25519PublicKey):
    key = re.sub(r"\s+", "", key)
    if not key.startswith(PREFIX) or "." not in key:
        raise ValueError("not an Engine Room key")
    p, s = key[len(PREFIX):].split(".", 1)
    data, sig = unb64u(p), unb64u(s)
    if b64u(data) != p or b64u(sig) != s:
        raise ValueError("key is not in canonical form")
    pub.verify(sig, data)            # raises InvalidSignature
    f = data.decode("utf-8").split("|")
    return {"version": f[0], "product": f[1], "edition": f[2], "serial": int(f[3]),
            "name": f[4], "email": f[5], "issued": f[6]}

def cmd_verify(args):
    try:
        print(json.dumps(verify(args.key, public_from_header()), indent=2))
    except (InvalidSignature, ValueError, IndexError) as e:
        sys.exit(f"INVALID: {e or 'signature does not match'}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="Discover Your Tone licence tool")
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("init");   a.add_argument("--force", action="store_true"); a.add_argument("--label")
    a = sub.add_parser("issue");  a.add_argument("--name", required=True); a.add_argument("--email", required=True)
    a.add_argument("--edition", default="founder", choices=list(EDITIONS)); a.add_argument("--order")
    a = sub.add_parser("batch");  a.add_argument("csv"); a.add_argument("--edition", default="founder", choices=list(EDITIONS))
    a = sub.add_parser("verify"); a.add_argument("key")
    args = ap.parse_args()
    {"init": cmd_init, "issue": cmd_issue, "batch": cmd_batch, "verify": cmd_verify}[args.cmd](args)
